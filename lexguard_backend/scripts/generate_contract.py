"""Generate Zod validation from Pydantic; --check fails on stale client artifacts."""
import argparse
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from models.schemas import AnalysisResponse

root = Path(__file__).resolve().parents[2]
schema = AnalysisResponse.model_json_schema()
defs = schema.pop("$defs")
lines = ['// Generated by lexguard_backend/scripts/generate_contract.py. Do not edit.', 'import { z } from "zod"', '']
emitted = set()


def convert(item):
    if "$ref" in item:
        name = item["$ref"].rsplit("/", 1)[-1]
        emit(name, defs[name])
        return name + "Schema"
    if "const" in item:
        return "z.literal(" + json.dumps(item["const"]) + ")"
    if "enum" in item:
        return "z.enum(" + json.dumps(item["enum"]) + ")"
    if "anyOf" in item:
        return "z.union([" + ", ".join(convert(part) for part in item["anyOf"]) + "])"
    kind = item.get("type")
    if kind == "object":
        required = item.get("required", [])
        entries = [json.dumps(key) + ": " + convert(value) + ("" if key in required else ".optional()") for key, value in item.get("properties", {}).items()]
        return "z.object({\n  " + ",\n  ".join(entries) + "\n}).strict()"
    if kind == "array":
        value = "z.array(" + convert(item["items"]) + ")"
        if "maxItems" in item:
            value += f'.max({item["maxItems"]})'
        return value
    value = {"string": "z.string()", "integer": "z.number().int()", "number": "z.number().finite()", "boolean": "z.boolean()", "null": "z.null()"}[kind]
    for field, method in [("minimum", "min"), ("maximum", "max"), ("minLength", "min"), ("maxLength", "max")]:
        if field in item:
            value += f'.{method}({item[field]})'
    return value


def emit(name, item):
    if name in emitted:
        return
    value = convert(item)
    lines.append(f"export const {name}Schema = {value}\n")
    lines.append(f"export type {name} = z.infer<typeof {name}Schema>\n")
    emitted.add(name)


emit("AnalysisResponse", schema)
output = root / "lexguard_frontend/lib/analysis-contract.ts"
content = "\n".join(lines)
if "--check" in sys.argv:
    if not output.exists() or output.read_text() != content:
        raise SystemExit("Client schema is stale: run python3 lexguard_backend/scripts/generate_contract.py")
else:
    output.write_text(content)
print("Client contract is current")
